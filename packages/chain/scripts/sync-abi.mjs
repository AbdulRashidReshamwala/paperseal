#!/usr/bin/env node
// Copies the ExamRegistry ABI, deployed bytecode and `board` immutable offsets from the Foundry
// artifact into src/abi.ts. The bytecode lets a reader check that an address is a real ExamRegistry.
// `make abi` runs this after `forge build`. Arguments override the paths for tests.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const artifactPath =
  process.argv[2] ?? resolve(here, '../../../contracts/out/ExamRegistry.sol/ExamRegistry.json');
const outputPath = process.argv[3] ?? resolve(here, '../src/abi.ts');

function fail(message) {
  console.error(`sync-abi: ${message}`);
  process.exit(1);
}

if (!existsSync(artifactPath)) {
  fail(`${artifactPath} does not exist. Run \`forge build\` in contracts/ first, or use \`make abi\`.`);
}

let artifact;
try {
  artifact = JSON.parse(readFileSync(artifactPath, 'utf8'));
} catch (error) {
  fail(`${artifactPath} is not valid JSON: ${error.message}`);
}
const { abi, deployedBytecode } = artifact;
if (!Array.isArray(abi) || abi.length === 0) fail(`${artifactPath} has no abi array.`);

// The runtime code, with zeros where the constructor writes the `board` immutable.
const bytecode = deployedBytecode?.object;
if (typeof bytecode !== 'string' || !/^0x([0-9a-fA-F]{2})+$/.test(bytecode)) {
  fail(`${artifactPath} has no deployedBytecode.object hex string.`);
}
// ExamRegistry has one immutable, `board`, so there must be exactly one id, each use one word long.
const immutables = Object.values(deployedBytecode.immutableReferences ?? {});
if (immutables.length !== 1) {
  fail(`${artifactPath} has ${immutables.length} immutables, expected exactly one (board).`);
}
const references = immutables[0];
if (!Array.isArray(references) || references.length === 0) fail(`${artifactPath} has no board immutable references.`);
const size = (bytecode.length - 2) / 2;
for (const { start, length } of references) {
  if (length !== 32) fail(`${artifactPath} has a board immutable reference ${length} bytes long, expected 32.`);
  if (!Number.isInteger(start) || start < 0 || start + length > size) {
    fail(`${artifactPath} has a board immutable reference at ${start}, outside the ${size}-byte code.`);
  }
}
const boardOffsets = references.map(({ start }) => start).sort((a, b) => a - b);

const source = `// Generated by scripts/sync-abi.mjs from contracts/out. Do not edit by hand.
export const examRegistryAbi = ${JSON.stringify(abi, null, 2)} as const;

/** The deployed code, with the \`board\` immutable zeroed at each of \`boardOffsets\` (byte offsets, 32 bytes each). */
export const examRegistryRuntime = {
  bytecode: '${bytecode.toLowerCase()}',
  boardOffsets: [${boardOffsets.join(', ')}],
} as const;
`;
writeFileSync(outputPath, source);
console.log(`sync-abi: wrote ${abi.length} ABI entries and ${size} bytes of runtime code to ${outputPath}`);
