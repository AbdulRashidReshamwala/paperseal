#!/usr/bin/env node
// Copies the ExamRegistry ABI from the Foundry artifact into src/abi.ts.
// `make abi` runs this after `forge build`. Arguments override the paths for tests.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const artifactPath =
  process.argv[2] ?? resolve(here, '../../../contracts/out/ExamRegistry.sol/ExamRegistry.json');
const outputPath = process.argv[3] ?? resolve(here, '../src/abi.ts');

function fail(message) {
  console.error(`sync-abi: ${message}`);
  process.exit(1);
}

if (!existsSync(artifactPath)) {
  fail(`${artifactPath} does not exist. Run \`forge build\` in contracts/ first, or use \`make abi\`.`);
}

let abi;
try {
  abi = JSON.parse(readFileSync(artifactPath, 'utf8')).abi;
} catch (error) {
  fail(`${artifactPath} is not valid JSON: ${error.message}`);
}
if (!Array.isArray(abi) || abi.length === 0) fail(`${artifactPath} has no abi array.`);

const source = `// Generated by scripts/sync-abi.mjs from contracts/out. Do not edit by hand.
export const examRegistryAbi = ${JSON.stringify(abi, null, 2)} as const;
`;
writeFileSync(outputPath, source);
console.log(`sync-abi: wrote ${abi.length} ABI entries to ${outputPath}`);
